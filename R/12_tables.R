  w("| ", labs[[rownames(sm)[i]]], " | ",
    sprintf("%.2f (%.2f-%.2f)", exp(sm[i,1]), exp(ci[i,1]), exp(ci[i,2])), " | ", pv(sm[i,4]), " |")
lrt <- anova(glm(adopter ~ 1, data = hc, family = binomial), fit, test = "LRT")
ph <- predict(fit, type = "response"); n1 <- sum(hc$adopter); n0 <- nrow(hc) - n1
auc <- (sum(rank(ph)[hc$adopter == 1]) - n1 * (n1 + 1) / 2) / (n1 * n0)
dm <- d[hospitalid %in% hc$hospitalid & !is.na(teaching) & !is.na(beds) & !is.na(region_f)]
v0 <- as.numeric(VarCorr(glmer(any_delirium_strict ~ 1 + (1|hospitalid), data = dm,
                               family = binomial, nAGQ = 0))$hospitalid)
v1 <- as.numeric(VarCorr(glmer(any_delirium_strict ~ teaching + beds + region_f + (1|hospitalid),
                               data = dm, family = binomial, nAGQ = 0))$hospitalid)

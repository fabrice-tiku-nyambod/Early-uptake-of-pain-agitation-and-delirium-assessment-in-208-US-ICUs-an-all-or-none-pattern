icc <- function(m) { v <- as.numeric(VarCorr(m)$hospitalid); v / (v + pi^2/3) }
w("| Outcome | Model | ICC | Structural non-adopter fraction (95% CI) | LRT P |")
w("|---|---|---|---|---|")
zibb <- function(col) {
  dat <- d[, .(n = .N, k = sum(get(col))), by = hospitalid][n >= MIN_STAYS]
  f0 <- function(p) { a <- exp(p[1]); b <- exp(p[2])
    -sum(lchoose(dat$n, dat$k) + lbeta(dat$k + a, dat$n - dat$k + b) - lbeta(a, b)) }
  f1 <- function(p) { a <- exp(p[1]); b <- exp(p[2]); pi0 <- plogis(p[3])
    l <- lchoose(dat$n, dat$k) + lbeta(dat$k + a, dat$n - dat$k + b) - lbeta(a, b)
    -sum(ifelse(dat$k == 0, log(pi0 + (1 - pi0) * exp(l)), log(1 - pi0) + l)) }
  A <- optim(c(0, 0), f0, method = "BFGS"); B <- optim(c(A$par, 0), f1, method = "BFGS")
  lr <- 2 * (A$value - B$value)
  set.seed(20260820)
  bs <- replicate(2000, { i <- sample(nrow(dat), replace = TRUE); dd <- dat[i]
    g <- function(p) { a <- exp(p[1]); b <- exp(p[2]); pi0 <- plogis(p[3])
      l <- lchoose(dd$n, dd$k) + lbeta(dd$k + a, dd$n - dd$k + b) - lbeta(a, b)
      -sum(ifelse(dd$k == 0, log(pi0 + (1 - pi0) * exp(l)), log(1 - pi0) + l)) }
    tryCatch(plogis(optim(c(0, 0, 0), g, method = "BFGS")$par[3]), error = function(e) NA_real_) })
  bs <- bs[!is.na(bs)]
  list(pi0 = plogis(B$par[3]), lo = quantile(bs, .025), hi = quantile(bs, .975),
       p = 0.5 * pchisq(lr, 1, lower.tail = FALSE))
}
for (nm in c("Delirium, validated instrument" = "any_delirium_strict",
             "Sedation" = "any_sedation_assess", "Pain" = "any_pain_assess")) {
  lab <- names(which(c("Delirium, validated instrument" = "any_delirium_strict",
                       "Sedation" = "any_sedation_assess", "Pain" = "any_pain_assess") == nm))
  m <- glmer(as.formula(sprintf("%s ~ 1 + (1|hospitalid)", nm)), data = d, family = binomial, nAGQ = 0)
  z <- zibb(nm)
  w("| ", lab, " | Empty | ", sprintf("%.3f", icc(m)),
    " | ", sprintf("%.2f (%.2f-%.2f)", z$pi0, z$lo, z$hi), " | ", pv(z$p), " |")
}

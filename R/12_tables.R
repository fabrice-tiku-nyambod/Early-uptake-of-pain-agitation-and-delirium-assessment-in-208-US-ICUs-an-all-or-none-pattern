ci <- suppressMessages(confint(fit)); sm <- summary(fit)$coefficients
labs <- c(teachingTeaching = "Teaching hospital (vs non-teaching)",
          `beds100 - 249` = "100-249 beds (vs <100)", `beds250 - 499` = "250-499 beds (vs <100)",
          `beds>= 500` = ">=500 beds (vs <100)", region_fSouth = "South (vs Midwest)",
          region_fWest = "West (vs Midwest)", region_fNortheast = "Northeast (vs Midwest)",
          size_k = "Cohort size, per 100 stays")

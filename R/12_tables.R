  pv(lrt$`Pr(>Chi)`[2]), "; McFadden pseudo-R2 ", sprintf("%.3f", 1 - fit$deviance / fit$null.deviance),
  "; area under the curve ", sprintf("%.3f", auc), ". ",
  "Hospital characteristics explained ", sprintf("%.1f%%", 100 * (v0 - v1) / v0),
  " of the between-hospital variance, moving the ICC from ", sprintf("%.3f", v0/(v0 + pi^2/3)),
  " to ", sprintf("%.3f", v1/(v1 + pi^2/3)), ".\n")


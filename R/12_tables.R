  sprintf("%.1f%%", 100 * as.numeric(VarCorr(m_adj)$hospitalid) / as.numeric(VarCorr(m_un)$hospitalid)), ". ",
  "The median odds ratio is not reported: with a large proportion of hospitals at exactly zero the model ",
  "approaches quasi-separation and the statistic is unstable.\n")

